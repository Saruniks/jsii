import { CodeMaker } from "codemaker";
import { Assembly } from "jsii-reflect";

export abstract class Crate {
  protected readonly assembly: Assembly;
  public readonly crateName: string;

  constructor(assembly: Assembly) {
    this.assembly = assembly;
    this.crateName = assembly.name;
    // this.crateName = assembly.name.replace(/[^a-zA-Z0-9_]/g, "-");
  }

  public emit(code: CodeMaker): void {
    code.openFile(`${this.crateName}/Cargo.toml`);
    code.line(`[package]`);
    code.line(`name = "${this.crateName}"`);
    code.line(`version = "${this.assembly.version}"`);
    code.line(`edition = "2024"`);
    code.closeFile(`${this.crateName}/Cargo.toml`);

    code.openFile(`${this.crateName}/src/lib.rs`);
    code.line(`// This file is generated by jsii-pacmak`);
    code.line(`// Do not edit this file manually.`);
    code.closeFile(`${this.crateName}/src/lib.rs`);
  }
}

export class RootCrate extends Crate {
  constructor(assembly: Assembly) {
    super(assembly);
  }

  public emit(code: CodeMaker): void {
    super.emit(code);
  }
}
